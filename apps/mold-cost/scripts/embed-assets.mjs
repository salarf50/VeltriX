import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const publicDir = join(root, 'public');
const sourceDir = join(root, 'src');
const assets = {};

async function visit(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) {
      await visit(absolute);
      continue;
    }
    const path = `/${relative(publicDir, absolute).split(sep).join('/')}`;
    const isBinary = /\.(?:png|jpe?g|webp|ico)$/i.test(path);
    assets[path] = (await readFile(absolute)).toString(isBinary ? 'base64' : 'utf8');
  }
}

await visit(publicDir);
if (assets['/index.html']) assets['/'] = assets['/index.html'];
await mkdir(sourceDir, { recursive: true });
const entries = Object.entries(assets).map(([path, value]) => {
  const isBinary = /\.(?:png|jpe?g|webp|ico)$/i.test(path);
  return `  ${JSON.stringify(path)}: { body: ${JSON.stringify(value)}, encoding: ${JSON.stringify(isBinary ? 'base64' : 'utf8')} }`;
}).join(',\n');
const output = `// Generated by scripts/embed-assets.mjs. Do not edit by hand.\nexport const APP_ASSETS: Record<string, { body: string; encoding: 'utf8' | 'base64' }> = {\n${entries}\n};\n`;
await writeFile(join(sourceDir, 'generated-assets.ts'), output, 'utf8');
console.log(`Embedded ${Object.keys(assets).length} PWA assets.`);
